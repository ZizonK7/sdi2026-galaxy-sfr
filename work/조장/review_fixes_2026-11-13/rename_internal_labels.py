"""Second pass after an outside read-through: replace revision-era labels that still showed in code and output tables.

Usage: python rename_internal_labels.py <notebook path>
Only cells 91, 93, 107, 111 change (sources). Outputs are regenerated by a full re-run afterwards.
"""
import json
import sys

path = sys.argv[1]
raw = open(path, 'rb').read()
crlf = b'\r\n' in raw
text = raw.decode('utf-8').replace('\r\n', '\n')
nb = json.loads(text)
assert json.dumps(nb, indent=1, sort_keys=True, ensure_ascii=False) + '\n' == text, 'unexpected file layout'

OLD_LABEL = 'Part II draft (11-07): env clf x linear reg (30 / 13)'
NEW_LABEL = '선형 두 단계 (분류기 30개 / 회귀기 13개)'
fixes = [  # (cell, old, new, expected count)
    (107, OLD_LABEL, NEW_LABEL, 2),
    (107, '"selected Δ vs Part II draft [95%]"', '"selected Δ vs 선형 두 단계(30/13) [95%]"', 1),
    (111, OLD_LABEL, NEW_LABEL, 1),
    (111, 'z_draft', 'z_linear_two_stage', 2),
    (111, '"Part II draft RMSE_dex"', '"선형 두 단계(30/13) RMSE_dex"', 1),
    (111, '# 11-06 실험에서 SFR = 0 비율로 나눈 낮은 밀도 경계', '# SFR = 0 비율로 나눈 낮은 밀도 경계(앞선 분석에서 정한 값)', 1),
    (91, '# 0.9는 D1에서 고른 값으로', '# 0.9는 log10(SFR + 1) 기준에서 고른 값으로', 1),
    (93, '선택 지표 log10(SFR + LOG_EPS)의 RMSE(기존 선택은 D1).', '선택 지표 log10(SFR + LOG_EPS)의 RMSE. 아래에서 D1 = log10(SFR + 1), D2 = log10(SFR + 0.01) 기준의 RMSE다(기존 선택은 D1).', 1),
    (93, '# 같은 계산을 D2·D3 정의까지 넓힌 원본은 별도 실행 기록에 있다.', '# 같은 계산을 다른 로그 정의까지 넓힌 원본은 별도 실행 기록에 있다.', 1),
]
for idx, old, new, count in fixes:
    src = ''.join(nb['cells'][idx]['source'])
    assert src.count(old) == count, (idx, old, src.count(old))
    nb['cells'][idx]['source'] = src.replace(old, new).splitlines(keepends=True)
out = json.dumps(nb, indent=1, sort_keys=True, ensure_ascii=False) + '\n'
if crlf:
    out = out.replace('\n', '\r\n')
open(path, 'wb').write(out.encode('utf-8'))
print('applied', len(fixes), 'replacements')
