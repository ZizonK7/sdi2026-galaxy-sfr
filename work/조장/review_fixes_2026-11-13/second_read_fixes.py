"""Third pass: fixes from a second outside read-through (Part II only).

Usage: python second_read_fixes.py <notebook path>
Sources of cells 93, 104, 111, 122 change. Outputs are regenerated by a full re-run afterwards.
"""
import json
import sys

path = sys.argv[1]
raw = open(path, 'rb').read()
crlf = b'\r\n' in raw
text = raw.decode('utf-8').replace('\r\n', '\n')
nb = json.loads(text)
assert json.dumps(nb, indent=1, sort_keys=True, ensure_ascii=False) + '\n' == text, 'unexpected file layout'

fixes = [  # (cell, old, new)
    # 추가 피처는 시드 42에서 고르고 시드 7에서 확인했다(101번 칸, 13.1절과 같게).
    (104, '학습 알고리즘은 학습 내부 5-fold(시드 42), 추가 피처는 학습 내부 5-fold × 시드 42·7(10개 분할)에서 골랐고, 판단 규칙은 결과 전에 정했다.',
          '학습 알고리즘은 학습 내부 5-fold(시드 42)에서 골랐다. 추가 피처는 학습 내부 5-fold(시드 42)에서 고른 뒤 시드 42·7(10개 분할)에서 다시 확인했다. 판단 규칙은 결과 전에 정했다.'),
    (122, '학습 알고리즘은 학습 내부 5-fold(시드 42), 추가 피처는 학습 내부 5-fold × 시드 42·7(10개 분할)에서 미리 정한 규칙으로 골랐다.',
          '학습 알고리즘은 학습 내부 5-fold(시드 42)에서 미리 정한 규칙으로 골랐다. 추가 피처는 학습 내부 5-fold(시드 42)에서 고른 뒤 시드 42·7(10개 분할)에서 다시 확인했다.'),
    # 주석의 실행 시간을 이 노트북의 출력(200~285초)에 맞춘다.
    (93, '원본은 별도 실행 기록에 있다. 약 5~6분.', '원본은 별도 실행 기록에 있다. 이 칸은 약 3~5분.'),
    # 10.2절의 "SFR > 100: 0.614 → 0.586"을 노트북 안에서 확인할 수 있게 34개 고정 모델의 구간별 RMSE 열을 더한다.
    (111, 'log_bins["선형 두 단계(30/13) RMSE_dex"] = bin_stats(z_linear_two_stage, sfr_bin)["RMSE_dex"]\n',
          'log_bins["선형 두 단계(30/13) RMSE_dex"] = bin_stats(z_linear_two_stage, sfr_bin)["RMSE_dex"]\n'
          'log_bins["34개 고정(문턱 0.9) RMSE_dex"] = bin_stats(to_log(val_models["34개 모델 (트리 400개 고정, 문턱 0.9)"]), sfr_bin)["RMSE_dex"]\n'),
    # 경계값은 이 노트북에서 계산한 값이 아니다. 그대로 밝힌다.
    (111, '# SFR = 0 비율로 나눈 낮은 밀도 경계(앞선 분석에서 정한 값)', '# 낮은 밀도 경계. 고정해 둔 상수이며 아래 밀도 구간표의 첫 경계와 같다'),
    # 이 비율은 0 출력(문턱 0.9)이 아니라 분류기 확률 0.5 기준이다.
    (111, '0 판정 {np.mean(p_fin[zl] <= 0.5):.1%}, ', 'P(SFR > 0) ≤ 0.5인 비율 {np.mean(p_fin[zl] <= 0.5):.1%}, '),
]
for idx, old, new in fixes:
    src = ''.join(nb['cells'][idx]['source'])
    assert src.count(old) == 1, (idx, old, src.count(old))
    nb['cells'][idx]['source'] = src.replace(old, new).splitlines(keepends=True)
out = json.dumps(nb, indent=1, sort_keys=True, ensure_ascii=False) + '\n'
if crlf:
    out = out.replace('\n', '\r\n')
open(path, 'wb').write(out.encode('utf-8'))
print('applied', len(fixes), 'replacements')
